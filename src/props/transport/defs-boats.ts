const H = Math.PI / 2;

const sailSeats: readonly Seat[] = SAILBOAT_BENCH.z.flatMap((z) => [
  hip(-SAILBOAT_BENCH.x, SAILBOAT_BENCH.y, z, H),
  hip(SAILBOAT_BENCH.x, SAILBOAT_BENCH.y, z, -H),
]);

const D = FLOAT_DECK;
const floatSeats: readonly Seat[] = [
  feet(-0.7, D, 2.8, 0),
  feet(0.7, D, 2.8, 0),
  feet(-0.7, D, -2.7, Math.PI),
  feet(0.7, D, -2.7, Math.PI),
  feet(-1.15, D, -1.6, -H),
  feet(1.15, D, -1.6, H),
];

const FLOAT_KEYS: Readonly<Record<FloatFigure, string>> = {
  fish: 'boat.float.fish',
  swan: 'boat.float.swan',
  lighthouseCake: 'boat.float.lighthouseCake',
  flowerArch: 'boat.float.flowerArch',
};

const floats: PropDef[] = FLOAT_FIGURES.map((f) =>
  def({
    key: FLOAT_KEYS[f],
    build: (q) => paradeFloat(q, f),
    footprint: [3.0, 8.0],
    family: 'boat',
    size: 'large',
    tint: 'blue',
    waterline: true,
    seats: floatSeats,
    tags: ['festival', 'parade'],
  }),
);

